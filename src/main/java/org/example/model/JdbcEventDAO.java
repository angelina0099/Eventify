package org.example.model;

import org.example.database.DatabaseConnection;
import org.example.exceptions.EventNotFoundException;

import java.sql.Connection;
import java.sql.Date;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;

public class JdbcEventDAO {

    private final DatabaseConnection databaseConnection;

    public JdbcEventDAO(DatabaseConnection databaseConnection) {
        this.databaseConnection = databaseConnection;
    }

    public void createTableIfNeeded() throws SQLException {
        String sql = "CREATE TABLE IF NOT EXISTS events ("
                + "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "name VARCHAR(255) NOT NULL, "
                + "description TEXT NOT NULL, "
                + "event_date DATE NOT NULL, "
                + "location VARCHAR(255) NOT NULL)";

        try (Connection connection = databaseConnection.getConnection();
             Statement statement = connection.createStatement()) {
            statement.executeUpdate(sql);
        }
    }

    public Event addEvent(Event event) throws SQLException {
        String sql = "INSERT INTO events (name, description, event_date, location) "
                + "VALUES (?, ?, ?, ?)";

        try (Connection connection = databaseConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            statement.setString(1, event.getName());
            statement.setString(2, event.getDescription());
            statement.setDate(3, Date.valueOf(event.getDate()));
            statement.setString(4, event.getLocation());
            statement.executeUpdate();

            try (ResultSet keys = statement.getGeneratedKeys()) {
                if (!keys.next()) {
                    throw new SQLException("PostgreSQL n'a pas retourné l'identifiant de l'événement.");
                }
                event.setId(keys.getInt(1));
            }
        }
        return event;
    }

    public ArrayList<Event> getAllEvents() throws SQLException {
        String sql = "SELECT id, name, description, event_date, location FROM events ORDER BY id";
        ArrayList<Event> events = new ArrayList<>();

        try (Connection connection = databaseConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql);
             ResultSet results = statement.executeQuery()) {
            while (results.next()) {
                events.add(readEvent(results));
            }
        }
        return events;
    }

    public Event findEventById(int id) throws SQLException, EventNotFoundException {
        String sql = "SELECT id, name, description, event_date, location FROM events WHERE id = ?";

        try (Connection connection = databaseConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setInt(1, id);
            try (ResultSet results = statement.executeQuery()) {
                if (results.next()) {
                    return readEvent(results);
                }
            }
        }
        throw new EventNotFoundException("Aucun événement trouvé avec l'identifiant " + id + ".");
    }

    public ArrayList<Event> findEventsByName(String name) throws SQLException {
        String sql = "SELECT id, name, description, event_date, location "
                + "FROM events WHERE LOWER(name) = LOWER(?) ORDER BY id";
        ArrayList<Event> events = new ArrayList<>();

        try (Connection connection = databaseConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, name);
            try (ResultSet results = statement.executeQuery()) {
                while (results.next()) {
                    events.add(readEvent(results));
                }
            }
        }
        return events;
    }

    public Event updateEvent(Event event) throws SQLException, EventNotFoundException {
        String sql = "UPDATE events SET name = ?, description = ?, event_date = ?, location = ? WHERE id = ?";

        try (Connection connection = databaseConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, event.getName());
            statement.setString(2, event.getDescription());
            statement.setDate(3, Date.valueOf(event.getDate()));
            statement.setString(4, event.getLocation());
            statement.setInt(5, event.getId());
            if (statement.executeUpdate() == 0) {
                throw new EventNotFoundException(
                        "Aucun événement trouvé avec l'identifiant " + event.getId() + "."
                );
            }
        }
        return event;
    }

    public void deleteEvent(int id) throws SQLException, EventNotFoundException {
        String sql = "DELETE FROM events WHERE id = ?";

        try (Connection connection = databaseConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setInt(1, id);
            if (statement.executeUpdate() == 0) {
                throw new EventNotFoundException("Aucun événement trouvé avec l'identifiant " + id + ".");
            }
        }
    }

    private Event readEvent(ResultSet results) throws SQLException {
        return new Event(
                results.getInt("id"),
                results.getString("name"),
                results.getString("description"),
                results.getDate("event_date").toLocalDate(),
                results.getString("location")
        );
    }
}
